# `category` is the entry in a domain's table that this pair was generated from, and
# it is what a generator hold-out is expressed in terms of. The hand-written matched
# packs have no table behind them, so theirs defaults to the want itself.
Family = collections.namedtuple("Family", "want target category", defaults=(None,))


@dataclasses.dataclass(frozen=True)
class Catalogue:
    """One domain's validated pairs.

    `listing` is the template a target is rendered into. `generic` is on topic and
    true of everything on the page: it is the unit that lifts the whole slate, so it
    is the realistic way to invent a reason, and until it existed nothing here
    exercised `min_specificity`.

    `requests` are request-shaped lines for things that are *not* on the page. They
    close a shortcut: when every distractor is off-topic junk ("winter tyres for an
    estate car"), the planted cause is the only line that reads like someone asking
    for something, and a model can score well by finding the request-shaped line
    without learning which listing it matches. There are enough of them here to fill
    the widest slate without repeating one.

    `pairs` is (category, want, target). Several pairs share a category: they are
    different phrasings of the same underlying thing, which is what makes the plant
    string hard to memorise while leaving the label identical. The category is the
    unit a hold-out is expressed in, because holding out a phrasing would leave the
    same semantic pair in training under another wording.
    """

    listing: str
    generic: str
    requests: tuple[str, ...]
    pairs: tuple[tuple[str, str, str], ...]

    def categories(self) -> tuple[str, ...]:
        """Every distinct category, in a fixed order."""
        seen = []
        for category, _want, _target in self.pairs:
            if category not in seen:
                seen.append(category)
        return tuple(seen)

    def usable(self, skip: frozenset[str]) -> tuple[str, ...]:
        return tuple(name for name in self.categories() if name not in skip)

    def families(self, rng: random.Random, count: int, skip: frozenset[str]) -> list[Family]:
        """`count` families, each a different category, each a random phrasing of it.

        Distinct categories, never two phrasings of one: two candidates whose
        listings are the same kind of thing would both satisfy the planted want, and
        that is a wrong label rather than a hard case.
        """
        available = self.usable(skip)
        if count > len(available):
            raise ValueError(
                "asked for %d families from %d usable categories; widen the table "
                "rather than drawing a category twice" % (count, len(available))
            )
        chosen = rng.sample(available, count)
        by_category = {}
        for category, want, target in self.pairs:
            by_category.setdefault(category, []).append((want, target))
        out = []
        for category in chosen:
            want, target = rng.choice(by_category[category])
            out.append(Family(want, target, category))
        return out

    def unit_counts(self, noise: int) -> tuple[int, ...]:
        """The evidence-set sizes this domain's distractor pools can fill.

        Stated for the same reason as `widths`. A control case is the binding one: it
        has no planted unit, so it needs one more distractor than a planted case of
        the same size, and `_fill` refuses to draw one twice. The pools differ by
        domain because a decoy only counts as absent if nothing on the page answers
        it, and a domain whose categories cover many kinds of thing has fewer
        requests left that are genuinely about none of them.
        """
        out = []
        for units in (4, 6, 8, 12, 20, 30):
            wanted = units - 1
            decoys = round(wanted * DECOY_SHARE)
            if decoys <= len(self.requests) and wanted - decoys <= noise:
                out.append(units)
        return tuple(out)

    def widths(self, skip: frozenset[str]) -> tuple[int, ...]:
        """The slate widths this domain can actually fill, from the usual choices.

        Stated rather than silently clipped. An earlier version took
        `min(size, len(families))`, so four of six nominal widths collapsed to one
        value and every claim about cost against slate width was measured over a
        range the corpus never produced.
        """
        return tuple(size for size in (3, 4, 5, 6, 8, 10) if size <= len(self.usable(skip)))


