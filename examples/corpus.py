GENERIC = "generic"
KEY = "key"
# Units whose id starts with this are request-shaped distractors: they read like the
# plant and match nothing on the page. Counted separately, because citing one is a
# different and more interesting failure than citing a dishwasher manual.
DECOY = "d"
# Share of the filler units that are decoys rather than off-topic junk. Half, so a
# slate carries both kinds and neither can be the only thing a model learns from.
DECOY_SHARE = 0.5
# Categories reserved for evaluation, in folds. Holding out categories rather than
# cases is what the generator is for: a reserved pair appears in no training slate in
# any position, rather than appearing eighteen times with different filler around it.
#
# Why folds rather than one reserved set. The first version took the last two entries
# of each domain's table -- deterministic, fixed before any run, and biased. Measured
# on the base model with language and domain held comparable, those categories scored
# 54.4% recall against 29.2% for the rest, so they were the *easier* ones and the
# split was not a sample of anything. Every category now sits in exactly one fold, so
# running all four estimates transfer over the whole table with no selection at all,
# and on four times the cases.
CATEGORY_FOLDS = 4
# Reserve nothing. The folds exist to measure what the adapter generalises to, and
# that measurement is finished; the adapter that ships is then trained on everything,
# because a category held out of the final run is one the product is simply worse at
# for no remaining reason. What still gates it is the held-back slates and the three
# general-ranking guards, neither of which this affects.
NO_FOLD = -1


def category_fold(index: int = 0) -> frozenset[str]:
    """The categories reserved by one fold, or none at all for `NO_FOLD`.

    Stratified within each domain rather than drawn from the pool, and that is not
    tidiness. `restaurants` carries five categories and a slate needs three distinct
    ones, so an unstratified fold that happened to reserve three of the five would
    leave a domain unable to produce a case at all. Dealing each domain's categories
    round-robin bounds the loss at one more than a quarter, whatever the shuffle.

    Seeded and exhaustive, so the folds partition the table: every category is held
    out by exactly one fold and trained on by the other three.
    """
    if index == NO_FOLD:
        return frozenset()
    if not 0 <= index < CATEGORY_FOLDS:
        raise ValueError(
            "fold %d outside 0..%d, or %d to reserve nothing"
            % (index, CATEGORY_FOLDS - 1, NO_FOLD)
        )
    rng = random.Random(20261122)
    reserved = set()
    for name in sorted(DOMAINS):
        shuffled = list(DOMAINS[name].categories())
        rng.shuffle(shuffled)
        reserved.update(shuffled[index::CATEGORY_FOLDS])
    return frozenset(reserved)


HELD_OUT_CATEGORIES = category_fold(0)


def _fill(rng: random.Random, items: list, units: int, searched: str, aside: str,
          requests, noise) -> None:
    """Pad a slate's evidence with distractors, never drawing the same line twice.

    Drawing with replacement is what the old corpus did, and it quietly destroyed the
    distractors it was paying for: `standout` subtracts the mean effect over the other
    candidates, so two copies of one line each measure as worth almost nothing when the
    other is still present. A duplicated request-shaped distractor was cited 2.8% of
    the time against 18.5% for a unique one.
    """
    wanted = max(units - len(items), 0)
    decoys = round(wanted * DECOY_SHARE)
    if decoys > len(requests) or wanted - decoys > len(noise):
        raise ValueError(
            "a slate of %d units needs %d distinct requests and %d distinct noise "
            "lines; the pools hold %d and %d. Widen the pools rather than sampling "
            "with replacement, because a repeated unit cancels itself out under "
            "leave-one-out and stops being a distractor."
            % (units, decoys, wanted - decoys, len(requests), len(noise))
        )
    for text in rng.sample(list(requests), decoys):
        items.append(Evidence("%s%d" % (DECOY, len(items)), searched, text))
    for text in rng.sample(list(noise), wanted - decoys):
        items.append(Evidence("n%d" % len(items), aside, text))


def _slate(rng: random.Random, listing: str, families, size: int):
    """One slate: one listing from each of several families, exactly one of which
    the planted request asks for. The family is returned so the caller can plant it.

    `size` is honoured rather than silently capped. The caller draws the families, and
    `Catalogue.families` raises if the table cannot supply that many distinct
    categories -- two families sharing a category would make the planted want true of
    both candidates, which is a wrong label rather than a hard case.
    """
    if len(families) != size:
        raise ValueError("asked for a slate of %d from %d families" % (size, len(families)))
    marked = [(family.target, index == 0) for index, family in enumerate(families)]
    rng.shuffle(marked)
    candidates = [
        Candidate("c%d" % index, "Option %d" % (index + 1), listing % text)
        for index, (text, _) in enumerate(marked)
    ]
    target = next(
        candidate.id for candidate, (_, is_target) in zip(candidates, marked) if is_target
    )
    return candidates, target, families[0]


def build_matched_case(rng: random.Random, index: int) -> dict:
    """One slate written wholly in a single language, kinds and listings alike.

    These are the only fully translated cases: the candidate text, the planted
    request, the distractors and the action verbs are all in one language. The mixed
    cases below localise the verb alone, which is why a held-out *language* says much
    less than a held-out category -- see `examples/compare.py`.
    """
    language = rng.choice(sorted(MATCHED))
    pack = MATCHED[language]
    # Three candidates and at most six units. The pack holds three families, three
    # request-shaped distractors and four noise lines -- all of it translation-checked
    # by two independent sentence encoders -- and `_fill` refuses to draw one twice,
    # so this is the width those pools support. A control case is the binding one: it
    # has no planted unit, so a sixth unit would need a fourth distinct request.
    #
    # The alternative was eleven languages' worth of new distractor translations that
    # nothing here can check, which would trade a documented limit for an unmeasured
    # one. So the unit-count axis is carried by the mixed cases, which run from 4 to
    # 30, and these carry the language axis.
    size = 3
    units = rng.choice([4, 6])
    planted = rng.random() > 0.3
    families = list(pack.families)
    rng.shuffle(families)
    candidates, target, family = _slate(rng, pack.listing, families[:size], size)
    searched, told = pack.kinds

    items = [Evidence(KEY, searched, family.want)] if planted else []
    items.append(Evidence(GENERIC, told, pack.generic))
    _fill(rng, items, units, searched, told, pack.requests, pack.noise)
    rng.shuffle(items)
    return {
        "id": index,
        "domain": "matched",
        "language": language,
        "condition": "matched",
        "candidates": candidates,
        "evidence": EvidenceSet(items),
        "target": target if planted else None,
        "key": KEY if planted else None,
        "category": (family.category or family.want) if planted else None,
        "size": len(candidates),
        "units": len(items),
    }


def build_case(rng: random.Random, index: int, skip: frozenset[str] = frozenset()) -> dict:
    """One slate, with the answer recorded beside it.

    `skip` leaves categories out, so the same builder serves training and evaluation:
    training passes the reserved set and the held-out evaluation draws only from it.
    """
    domain = rng.choice(sorted(DOMAINS))
    language = rng.choice(sorted(ACTIONS))
    catalogue = DOMAINS[domain]
    # The widths this domain can fill, which differ: a domain with five usable
    # categories cannot put ten distinct kinds of thing on a page, and pretending
    # otherwise is what the old silent `min` did.
    size = rng.choice(catalogue.widths(skip))
    units = rng.choice(catalogue.unit_counts(len(NOISE)))
    planted = rng.random() > 0.3
    families = catalogue.families(rng, size, skip)
    candidates, target, family = _slate(rng, catalogue.listing, families, size)
    searched, viewed, told = ACTIONS[language]

    items = [Evidence(KEY, searched, family.want)] if planted else []
    items.append(Evidence(GENERIC, told, catalogue.generic))
    _fill(rng, items, units, searched, viewed, catalogue.requests, NOISE)
    rng.shuffle(items)
    return {
        "id": index,
        "domain": domain,
        "language": language,
        "condition": "mixed",
        "candidates": candidates,
        "evidence": EvidenceSet(items),
        "target": target if planted else None,
        "key": KEY if planted else None,
        "category": family.category if planted else None,
        "size": len(candidates),
        "units": len(items),
    }
