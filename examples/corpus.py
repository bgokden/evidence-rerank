"""The planted-evidence corpus: pairs composed by a generator, kept by measurement.

Why it was rebuilt. The version this replaces held 60 distinct (want, target) pairs
across 1100 cases -- 18 cases per pair -- and 113 filler strings, and three separate
weaknesses came out of that one number. A split that holds out *cases* leaks, because
the pair being tested appears eighteen times in training; a lookup table of 60 entries
learned from half the cases scored 100% on the other half. A blacklist of the 113
filler strings located the planted unit with no semantics at all. And the
request-shaped distractors were drawn with replacement from pools of three, so a line
appeared 3.3 times in a slate on average and leave-one-out cancelled it -- a unique
distractor was cited 18.5% of the time against 2.8% for a duplicated one, making them
about two and a half times weaker than intended.

What is here now: 48 categories carrying 512 validated pairs, 12 of the categories
reserved for evaluation, and distractor pools large enough that no slate repeats a
line. Each `pairs` entry is (category, want, target). Several entries share a
category, being different phrasings of the same underlying thing, which is what makes
the plant string hard to memorise while leaving the label identical. The category is
the unit the hold-out is expressed in: holding out a phrasing would leave the same
semantic pair in training under another wording.

Every pair here passed `examples/validate_corpus.py`, and the filtering is not a
formality -- 272 candidate pairs were dropped. Two findings came out of it that are
worth keeping.

The first: surface decoration is not free. The generator originally built variety by
appending a truth-neutral tail to each side -- " for a few nights", ". Courtyard at
the back" -- on the assumption that an aside cannot change which listing a request
picks out. Measured, it can. " within walking distance" moved "a Moroccan slow-cooked
stew restaurant" closer to "a souvlaki grill" than to its own "tagine house". Judged
all-or-nothing, where one bad tail disqualified its whole category, the six domains
retained between one and six categories out of fourteen. Judging each phrasing on its
own merits is what saved the design.

The second: there is a band, and it is narrower than it looks. The pairs easiest to
label unambiguously are the ones whose target restates the want -- and those are
exactly the ones a character-trigram matcher solves, which an earlier version of this
corpus did outright. Pushing the paraphrase apart buys resistance to lexical attack
and spends label clarity. The 48 categories that survive are the ones where both
hold, which is why some domains carry five and one carries fourteen: `courses` asks
about distinct subjects, while `restaurants` asks about cuisines, and cuisines sit
close together however carefully they are written.

Widths and unit counts are per domain and are stated rather than clipped, because the
pools differ. An earlier `min(size, len(families))` silently collapsed four of six
nominal widths onto one value, so every claim about cost against slate width was
measured over a range the corpus never produced.
"""

